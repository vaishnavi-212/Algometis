/** Public (JSON-safe) view of the registry for the browser and for LLM tool results. */
export function publicCatalog() {
  return Object.entries(ALGORITHMS).map(([id, a]) => ({
    id,
    name: a.name,
    category: a.category,
    families: a.families,
    inputKind: a.inputKind,
    complexity: a.complexity,
    whenToUse: a.whenToUse,
    pitfalls: a.pitfalls,
    sample: a.sample,
    rules: a.rules,
  }))
}
